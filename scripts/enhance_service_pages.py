def slug_from_path(path: Path) -> str:
    return path.stem  # 'swedish.html' -> 'swedish'


def render_deep_section(slug: str) -> str:
    content = SERVICE_CONTENT.get(slug)
    if not content:
        return ''
    parts = [
        f'\n  <section class="article-section {DEEP_MARKER}">',
        f'    <h2>{content["title"]} 심화 안내</h2>',
    ]
    for sec in content['sections']:
        parts.append(
            f'    <h3>{sec["h2"]}</h3>\n    <p>{sec["body"]}</p>'
        )
    parts.append('  </section>\n')
    return '\n'.join(parts)


def modify_jsonld(jsonld_str: str, url: str, headline: str, desc: str):
    changes = set()
    data = json.loads(jsonld_str)
    graph = data.get('@graph', [])

    has_article = any(obj.get('@type') == 'Article' for obj in graph)
    if not has_article and url and headline:
        article = {
            '@type': 'Article',
            '@id': f'{url}#article',
            'headline': headline,
            'description': desc or headline,
            'datePublished': '2026-05-12T09:00:00+09:00',
            'dateModified': '2026-05-17T09:00:00+09:00',
            'author': {
                '@type': 'Person',
                '@id': 'https://gandago.me/about/authors/jung-uijin.html#person',
                'name': '정의진',
                'url': 'https://gandago.me/about/authors/jung-uijin.html',
                'jobTitle': '편집장',
                'worksFor': {'@id': 'https://gandago.me/#org'},
            },
            'publisher': {'@id': 'https://gandago.me/#org'},
            'mainEntityOfPage': {'@id': url},
            'inLanguage': 'ko-KR',
            'image': 'https://gandago.me/assets/og-default.svg',
        }
        insert_at = 1
        for i, obj in enumerate(graph):
            if obj.get('@type') == 'Organization':
                insert_at = i + 1
                break
        graph.insert(insert_at, article)
        changes.add('article')

    data['@graph'] = graph
    return json.dumps(data, ensure_ascii=False, indent=2), changes


def process(path: Path) -> dict:
    html = path.read_text(encoding='utf-8')
    original = html
    actions = []
    slug = slug_from_path(path)
    if slug == 'index':
        return {'path': str(path.relative_to(ROOT)), 'actions': ['skip-index']}

    # h1 / canonical / description
    m = re.search(r'<h1[^>]*>\s*([^<]+?)\s*</h1>', html)
    h1 = m.group(1).strip() if m else ''
    m = re.search(r'<link\s+rel="canonical"\s+href="([^"]+)"', html)
    canonical = m.group(1) if m else ''
    m = re.search(r'<meta\s+name="description"\s+content="([^"]*)"', html)
    desc = m.group(1).strip() if m else ''

    # --- A. Byline ----------------------------------------------------
    if 'class="post-meta service-byline"' not in html:
        # Inject after h1 + first <p>...</p> in page-header
        pattern = re.compile(r'(<h1[^>]*>[^<]+</h1>\s*<p>[^<]*</p>)', re.S)
        new_html, n = pattern.subn(
            lambda m: m.group(1) + BYLINE_TEMPLATE, html, count=1
        )
        if n:
            html = new_html
            actions.append('byline')

    # --- B. Deep content section before safety callout ----------------
    if DEEP_MARKER not in html:
        deep = render_deep_section(slug)
        if deep:
            # Find "안전 안내" callout section and insert before it
            pattern = re.compile(
                r'(\n\s*<section class="article-section">\s*<div class="callout info">'
                r'<strong>안전 안내:)',
                re.S,
            )
            new_html, n = pattern.subn(
                lambda m: deep + m.group(1), html, count=1
            )
            if n:
                html = new_html
                actions.append('deep-section')

    # --- B2. Extra paragraph (only if page is short or always inject) -
    if EXTRA_MARKER not in html:
        extra = render_extra_section(slug)
        if extra:
            pattern = re.compile(
                r'(\n\s*<section class="article-section">\s*<div class="callout info">'
                r'<strong>안전 안내:)',
                re.S,
            )
            new_html, n = pattern.subn(
                lambda m: extra + m.group(1), html, count=1
            )
            if n:
                html = new_html
                actions.append('extra-section')

    # --- C. Article schema ---------------------------------------------
    m = JSONLD_BLOCK_RE.search(html)
    if m and canonical and h1:
        prefix, jsonld_str, suffix = m.group(1), m.group(2), m.group(3)
        try:
            new_jsonld, changes = modify_jsonld(
                jsonld_str, canonical, h1, desc
            )
            if changes:
                html = html[: m.start(2)] + new_jsonld + html[m.end(2):]
                actions.extend(sorted(changes))
        except json.JSONDecodeError as e:
            actions.append(f'jsonld-skip:{e.msg[:30]}')

    if html != original:
        path.write_text(html, encoding='utf-8')
    return {'path': str(path.relative_to(ROOT)), 'actions': actions}


def main():
    pages = sorted(SERVICES_DIR.glob('*.html'))
    summary = {}
    no_change = 0
    for p in pages:
        r = process(p)
        if not r['actions']:
            no_change += 1
        for a in r['actions']:
            summary[a] = summary.get(a, 0) + 1
    summary['no-change'] = no_change
    print(f'Processed {len(pages)} service pages')
    for k, v in sorted(summary.items()):
        print(f'  {k}: {v}')


if __name__ == '__main__':
    main()
