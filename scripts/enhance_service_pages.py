def render_extra_section(slug: str) -> str:
    extra = SERVICE_EXTRA.get(slug)
    if not extra:
        return ''
    return (
        f'\n  <section class="article-section {EXTRA_MARKER}">'
        f'\n    <h3>이용 시 자주 묻는 추가 안내</h3>'
        f'\n    <p>{extra}</p>'
        f'\n  </section>\n'
    )


